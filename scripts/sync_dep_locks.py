"""Regenerate dependency locks and synchronize release-policy dependency pins.

`--check` is deterministic and network-free so it can gate CI: it verifies that
every exact pin in each `.in` input appears in its committed compiled lock, that
release-policy pins match the committed manifests, and that `uv.lock` matches
`pyproject.toml`. Full lock re-resolution happens only in sync mode, because a
fresh resolve legitimately drifts whenever transitive releases appear upstream.
Direct declarations must be markerless; marker-qualified direct declarations are
rejected rather than semantically compared.
"""

