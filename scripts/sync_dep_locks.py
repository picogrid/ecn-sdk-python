# might reasonably add. An option outside these sets is an error, not a guess.
COMPILE_BARE_FLAGS = frozenset({"--generate-hashes", "--universal", "--no-strip-extras"})
# `-c/--constraints` is deliberately absent: uv resolves against a constraints
# file, but nothing here inspects its declarations, so skipping it would let a
# constraint change the resolution unaudited. It is an unmodeled option until
# something reads it.
