def _in_package(module_name: str, package: str) -> bool:
    return module_name == package or module_name.startswith(f"{package}.")


@contextlib.contextmanager
def _runtime_modules(
    package_root: Path, package: str
) -> Iterator[tuple[types.ModuleType, types.ModuleType, types.ModuleType]]:
    """Import the documented package from one search root, then restore state.

    Documentation extraction must read the exact package under ``package_root``
    even when another copy is already imported, but it must not leave the
    interpreter's module table rebound for anything running afterwards.
    """

    root = package_root.resolve()
    owned = {name: module for name, module in sys.modules.items() if _in_package(name, package)}
    loaded = sys.modules.get(package)
    loaded_file = Path(cast(str, getattr(loaded, "__file__", ""))).resolve() if loaded else None
    if loaded_file is not None and root not in loaded_file.parents:
        for name in owned:
            del sys.modules[name]
    sys.path.insert(0, str(root))
    try:
        public = importlib.import_module(package)
        testing = importlib.import_module(f"{package}.testing")
        workflows = importlib.import_module(f"{package}.workflows")
        for module in (public, testing, workflows):
            resolved = Path(cast(str, getattr(module, "__file__", ""))).resolve()
            if root not in resolved.parents:
                raise RuntimeError(
                    f"{module.__name__} resolved outside the requested package root; "
                    "refusing to mix source-tree and installed-package metadata"
                )
        yield public, testing, workflows
    finally:
        sys.path.remove(str(root))
        for name in [name for name in sys.modules if _in_package(name, package)]:
            del sys.modules[name]
        sys.modules.update(owned)


