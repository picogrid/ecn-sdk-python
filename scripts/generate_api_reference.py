def _site_route(route: str) -> str:
    """Build a mount-neutral, root-absolute site route.

    The documentation mount (Astro ``base``) is deployment configuration; the
    build-time link rewriter in ``docs/astro.config.mjs`` prefixes the configured
    base, so generated content never embeds it.
    """
    cleaned = route.strip("/")
    if not cleaned:
        return "/"
    return f"/{cleaned}/"


